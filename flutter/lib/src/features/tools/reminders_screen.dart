/// Round 18 — Reminders tool screen (display).
/// Round 47 — WRITE actions, porting native `RemindersScreen.kt` +
/// `AddReminderSheet`:
///
/// - Data: the `reminders` JSON blob on the profile, via
///   `TabsBackend.fetchProfile()` → `decodeProfileList`. There is NO
///   per-row endpoint: every mutation re-pushes the WHOLE list via
///   `POST /api/sync/profile` field `reminders` (native parity), and
///   the write model is the RAW pulled rows ([ReminderDocument]) so
///   untouched rows — including keys this model does not know —
///   survive byte-for-byte (the PR #28 whole-list integrity lesson,
///   Round 39's MedicationDocument pattern).
/// - Create: FAB "New Reminder" → permission gate → bottom sheet.
///   Native has NO edit UI, but the founder asked for it explicitly:
///   tapping a card opens the same sheet prefilled and saving
///   updates that row in place, keeping its `id`.
/// - Delete: trailing ✕ per card, immediate, no confirmation
///   (native parity). Toggle: a real Switch flips `isEnabled`.
/// - Alarms: after every successful push the device runs a FULL
///   alarm reconcile across all current reminders via
///   `reminder_alarm_sync.dart` (fix-round ID block scheme; a
///   delete first cancels the deleted reminder's whole block, then
///   the reconcile reschedules any surviving row that shared its
///   id — Vera B4); a notification failure never fails the save —
///   it surfaces as a non-blocking note.
/// - Writes are SERIALIZED (Vera B3): one push in flight at a
///   time; while a push is pending every write control (FAB, card
///   tap, Switch, ✕, sheet save path) is disabled or its tap is
///   dropped, and the failure-path reload runs inside the same
///   serialized section so it can never race an in-flight push.
/// - On push failure: error SnackBar + reload from the server; the
///   UI never claims an unsaved state.

/// One entry of the `reminders` profile blob. Defaults mirror native
/// `Reminder.kt` (fixedHour 12, interval 2h, window 8:00–21:00, enabled).
class ReminderModel {
  /// The blob's integer identity (native Room autogenerated id).
  /// There is no server id — this IS the identity. 0 when absent.
  final int id;
  final String title;
  final String type; // "FIXED" | "INTERVAL"
  final int fixedHour;
  final int fixedMinute;
  final int intervalHours;
  final int intervalMinutes;
  final int startHour;
  final int startMinute;
  final int endHour;
  final int endMinute;
  final bool isEnabled;
  final List<DayTimeConfig> dayConfigs;

  const ReminderModel({
    required this.id,
    required this.title,
    required this.type,
    required this.fixedHour,
    required this.fixedMinute,
    required this.intervalHours,
    required this.intervalMinutes,
    required this.startHour,
    required this.startMinute,
    required this.endHour,
    required this.endMinute,
    required this.isEnabled,
    required this.dayConfigs,
  });

  factory ReminderModel.fromJson(Map<String, dynamic> json) {
    final dayConfigs = <DayTimeConfig>[];
    final rawDays = json['daysOfWeekConfig'];
    if (rawDays is String && rawDays.trim().isNotEmpty) {
      try {
        // Tolerates a JSON list (what native writes) or a single object.
        final decoded = TabsBackend.decodeProfileList(rawDays);
        for (final d in decoded) {
          dayConfigs.add(DayTimeConfig.fromJson(d));
        }
      } catch (_) {
        // Malformed day config → fall back to the fixed time.
      }
    } else if (rawDays is List) {
      for (final d in rawDays) {
        if (d is Map<String, dynamic>) {
          dayConfigs.add(DayTimeConfig.fromJson(d));
        }
      }
    }
    final type = '${json['type'] ?? 'FIXED'}'.toUpperCase();
    return ReminderModel(
      id: _asInt(json['id'], 0),
      title: '${json['title'] ?? ''}',
      type: type == 'INTERVAL' ? 'INTERVAL' : 'FIXED',
      fixedHour: _asInt(json['fixedHour'], 12),
      fixedMinute: _asInt(json['fixedMinute'], 0),
      intervalHours: _asInt(json['intervalHours'], 2),
      intervalMinutes: _asInt(json['intervalMinutes'], 0),
      startHour: _asInt(json['startHour'], 8),
      startMinute: _asInt(json['startMinute'], 0),
      endHour: _asInt(json['endHour'], 21),
      endMinute: _asInt(json['endMinute'], 0),
      // Round 48 — tolerant bool (shared parser, as in the
      // medication model): the old `!= false` check read a
      // string-serialized "false" (and numeric 0) as ENABLED.
      // Absent/unparseable keeps the native default: enabled.
      isEnabled: parseLooseBoolOrNull(json['isEnabled']) ?? true,
      dayConfigs: dayConfigs,
    );
  }
}

/// Parses reminder rows fail-soft: a row that throws is skipped instead
/// of killing the whole list. Never throws.
List<ReminderModel> parseReminderModels(
    List<Map<String, dynamic>> rows) {
  final out = <ReminderModel>[];
  for (final row in rows) {
    try {
      out.add(ReminderModel.fromJson(row));
    } catch (_) {
      // Skip the bad row; keep the rest.
    }
  }
  return out;
}

/// One row of native `DayTimeConfig` (Mon 9:00 AM, …).
class DayTimeConfig {
  /// java Calendar constant (SUNDAY=1 … SATURDAY=7) — the blob's
  /// own numbering, and the plugin `Day` enum's values.
  final int dayOfWeek;
  final String dayName;
  final bool isEnabled;
  final int hour;
  final int minute;

  const DayTimeConfig({
    required this.dayOfWeek,
    required this.dayName,
    required this.isEnabled,
    required this.hour,
    required this.minute,
  });

  factory DayTimeConfig.fromJson(Map<String, dynamic> json) {
    final name = '${json['dayName'] ?? ''}';
    final rawDay = _asInt(json['dayOfWeek'], 0);
    return DayTimeConfig(
      dayOfWeek: (rawDay >= 1 && rawDay <= 7)
          ? rawDay
          : dayOfWeekForDayName(name),
      dayName: name,
      // Round 48 — tolerant bool (shared parser): the old
      // `== true` check read a string-serialized "true" (and
      // numeric 1) as DISABLED, silently dropping that day's
      // alarm from the schedule summary and the alarm sync.
      isEnabled: parseLooseBoolOrNull(json['isEnabled']) ?? false,
      hour: _asInt(json['hour'], 9),
      minute: _asInt(json['minute'], 0),
    );
  }

  /// Native-shaped serialization of this day row (key order mirrors
  /// the native blob: dayOfWeek, dayName, isEnabled, hour, minute).
  Map<String, dynamic> toJson() => <String, dynamic>{
        'dayOfWeek': dayOfWeek,
        'dayName': dayName,
        'isEnabled': isEnabled,
        'hour': hour,
        'minute': minute,
      };
}

/// Calendar constant for a short day name ("Mon"…"Sun"); Monday (2)
/// when the name is missing/unknown, matching the Mon-first sheet.
int dayOfWeekForDayName(String dayName) {
  switch (dayName.trim()) {
    case 'Sun':
      return 1;
    case 'Mon':
      return 2;
    case 'Tue':
      return 3;
    case 'Wed':
      return 4;
    case 'Thu':
      return 5;
    case 'Fri':
      return 6;
    case 'Sat':
      return 7;
    default:
      return 2;
  }
}

int _asInt(dynamic v, int fallback) {
  if (v is num) return v.toInt();
  if (v is String) return int.tryParse(v) ?? fallback;
  return fallback;
}

/// Tolerant id parse for a raw blob row (server numbers may arrive
/// as strings). Null when there is no usable id.
int? reminderRowId(Map<String, dynamic> row) {
  final v = row['id'];
  if (v is num) return v.toInt();
  if (v is String) return int.tryParse(v);
  return null;
}

/// The id a NEW reminder row gets: max(existing ids) + 1, starting
/// at 1 — native Room-autogenerate parity over the blob identity.
int nextReminderId(List<Map<String, dynamic>> rows) {
  var maxId = 0;
  for (final row in rows) {
    final id = reminderRowId(row);
    if (id != null && id > maxId) maxId = id;
  }
  return maxId + 1;
}

/// Builds one reminder row in the exact native blob shape (all keys
/// verbatim). `daysOfWeekConfig` is the stringified JSON array of
/// ALL 7 day rows when [customDays] is on for a FIXED reminder, and
/// the empty string otherwise (native parity).
Map<String, dynamic> buildReminderRow({
  required int id,
  required String title,
  required String type,
  required int fixedHour,
  required int fixedMinute,
  required int intervalHours,
  required int intervalMinutes,
  required int startHour,
  required int startMinute,
  required int endHour,
  required int endMinute,
  required bool isEnabled,
  required bool customDays,
  required List<DayTimeConfig> dayConfigs,
}) {
  return <String, dynamic>{
    'id': id,
    'title': title,
    'type': type,
    'fixedHour': fixedHour,
    'fixedMinute': fixedMinute,
    'intervalHours': intervalHours,
    'intervalMinutes': intervalMinutes,
    'startHour': startHour,
    'startMinute': startMinute,
    'endHour': endHour,
    'endMinute': endMinute,
    'isEnabled': isEnabled,
    'daysOfWeekConfig': (type == 'FIXED' && customDays)
        ? jsonEncode(dayConfigs.map((d) => d.toJson()).toList())
        : '',
  };
}

/// Round 47 — the reminders blob as a WRITE model with raw-row
/// retention (Round 39's MedicationDocument pattern): mutations
/// start from the freshest pulled rows and change the minimum
/// possible — a toggle flips only `isEnabled` on the targeted raw
/// row, a delete removes exactly that row, an edit splices the
/// edited fields over the raw row (keys the editor does not know
/// survive), an add appends one native-shaped row. Untouched rows
/// encode back exactly as pulled. Ops address rows by RAW INDEX
/// (the index the screen renders), never by title.
class ReminderDocument {
  /// The raw decoded blob rows, in blob order.
  final List<Map<String, dynamic>> rawRows;

  /// Parsed models aligned with [rawRows] by index; null where a
  /// row could not be parsed (such rows are retained for writes but
  /// not rendered).
  final List<ReminderModel?> _models;

  ReminderDocument._(this.rawRows, this._models);

  factory ReminderDocument.fromRawRows(List<Map<String, dynamic>> rows) {
    final raw = [for (final r in rows) Map<String, dynamic>.of(r)];
    return ReminderDocument._(raw, [
      for (final r in raw)
        () {
          try {
            return ReminderModel.fromJson(r);
          } catch (_) {
            return null;
          }
        }(),
    ]);
  }

  static final ReminderDocument empty =
      ReminderDocument._(<Map<String, dynamic>>[], <ReminderModel?>[]);

  /// Raw indices of the renderable rows, in blob order.
  List<int> get visibleIndices => [
        for (var i = 0; i < _models.length; i++)
          if (_models[i] != null) i,
      ];

  /// The parsed model at raw index [rawIndex], or null.
  ReminderModel? modelAt(int rawIndex) =>
      (rawIndex >= 0 && rawIndex < _models.length)
          ? _models[rawIndex]
          : null;

  /// The whole list for the profile push: one row per raw row,
  /// untouched rows exactly as pulled.
  List<Map<String, dynamic>> encode() =>
      [for (final r in rawRows) Map<String, dynamic>.of(r)];

  ReminderDocument _withRows(List<Map<String, dynamic>> rows) =>
      ReminderDocument.fromRawRows(rows);

  /// Toggle: flips ONLY `isEnabled` on the raw row at [rawIndex].
  ReminderDocument toggledAt(int rawIndex, bool enabled) {
    if (rawIndex < 0 || rawIndex >= rawRows.length) return this;
    final rows = encode();
    rows[rawIndex] = {...rows[rawIndex], 'isEnabled': enabled};
    return _withRows(rows);
  }

  /// Edit: splices [row] over the raw row at [rawIndex] — the
  /// edited fields win, unknown raw keys survive, position and
  /// (via the caller's row) the `id` are preserved.
  ReminderDocument replacedAt(int rawIndex, Map<String, dynamic> row) {
    if (rawIndex < 0 || rawIndex >= rawRows.length) return this;
    final rows = encode();
    rows[rawIndex] = {...rows[rawIndex], ...row};
    return _withRows(rows);
  }

  /// Delete: removes exactly the raw row at [rawIndex].
  ReminderDocument removedAt(int rawIndex) {
    if (rawIndex < 0 || rawIndex >= rawRows.length) return this;
    final rows = encode()..removeAt(rawIndex);
    return _withRows(rows);
  }

  /// Add: appends one new native-shaped row.
  ReminderDocument appended(Map<String, dynamic> row) =>
      _withRows([...encode(), Map<String, dynamic>.of(row)]);
}

/// 12-hour clock label, matching native `formatTime` ("9:00 AM").
String formatTime12h(int hour, int minute) {
  final amPm = hour < 12 ? 'AM' : 'PM';
  final h12 = hour % 12 == 0 ? 12 : hour % 12;
  return '$h12:${minute.toString().padLeft(2, '0')} $amPm';
}

/// The schedule summary line, mirroring native `ReminderCard`'s
/// `timeLabel` logic verbatim.
String reminderScheduleSummary(ReminderModel r) {
  if (r.type == 'FIXED') {
    final enabled =
        r.dayConfigs.where((d) => d.isEnabled).toList();
    if (enabled.isNotEmpty) {
      return enabled
          .map((d) => '${d.dayName} ${formatTime12h(d.hour, d.minute)}')
          .join(', ');
    }
    return formatTime12h(r.fixedHour, r.fixedMinute);
  }
  final intervalStr = r.intervalHours > 0
      ? 'Every ${r.intervalHours}h'
      : 'Every ${r.intervalMinutes}m';
  return '$intervalStr  •  ${formatTime12h(r.startHour, r.startMinute)} to ${formatTime12h(r.endHour, r.endMinute)}';
}

/// CREATE permission gate (Juno F1), shared verbatim by the
/// Reminders create flow and the Health Coach reminder approval
/// (Round 48 fix round, Juno F2) so both run the SAME ordering:
///
/// 1. Exact-alarm gate FIRST: when exact alarms are unavailable,
///    an advisory dialog offers system settings (dismissing it
///    still continues the gate; scheduling falls back to inexact
///    alarms per the notification service).
/// 2. Notification rationale dialog ("Enable Notifications"):
///    the system POST_NOTIFICATIONS request fires ONLY from its
///    Allow button — never bare, never before the rationale.
/// 3. The caller may proceed ONLY when notification permission
///    is granted. When it is denied (Not now, or denied at the
///    system dialog), the caller must not write or claim a
///    reminder was set: a reminder must never show ON while it
///    can never fire, silently.
///
/// Returns whether the caller may proceed. When the system
/// request itself throws, [onNotificationsRequestError] runs
/// (the Reminders screen shows its alarm note there, exactly as
/// before this extraction) and the gate returns false.
Future<bool> runReminderCreatePermissionGate({
  required BuildContext context,
  required ReminderNotificationService notifs,
  VoidCallback? onNotificationsRequestError,
}) async {
  try {
    final exact = await notifs.canScheduleExact();
    if (!exact && context.mounted) {
      final openSettings = await showDialog<bool>(
        context: context,
        builder: (dialogContext) => AlertDialog(
          title: const Text('Exact alarms are off'),
          content: const Text(
              'Without exact alarm permission, reminders may arrive late. You can turn it on in system settings.'),
          actions: [
            TextButton(
              onPressed: () => Navigator.of(dialogContext).pop(false),
              child: const Text('Not now'),
            ),
            TextButton(
              onPressed: () => Navigator.of(dialogContext).pop(true),
              child: const Text('Open Settings'),
            ),
          ],
        ),
      );
      if (openSettings == true) {
        try {
          await notifs.requestExactAlarmsPermission();
        } catch (_) {
          // Advisory gate — the rationale step still runs below.
        }
      }
    }
  } catch (_) {
    // Advisory gate — the rationale step still runs below.
  }
  if (!context.mounted) return false;
  final allow = await showDialog<bool>(
    context: context,
    builder: (dialogContext) => AlertDialog(
      title: const Text('Enable Notifications'),
      content: const Text(
          'Tabs needs notification permission to send your reminders. Tap Allow to continue.'),
      actions: [
        TextButton(
          onPressed: () => Navigator.of(dialogContext).pop(false),
          child: const Text('Not now'),
        ),
        TextButton(
          onPressed: () => Navigator.of(dialogContext).pop(true),
          child: const Text('Allow'),
        ),
      ],
    ),
  );
  if (allow != true || !context.mounted) return false;
  try {
    return await notifs.requestNotificationsPermission();
  } catch (_) {
    onNotificationsRequestError?.call();
    return false;
  }
}

/// Round 18 — Reminders screen. Round 47 — full write actions.
///
/// [backend] and [notificationService] are injectable so widget
/// tests can drive the screen with fakes; production defaults to a
/// real [TabsBackend] and the local notifications service.
class RemindersScreen extends StatefulWidget {
  final TabsBackend? backend;
  final ReminderNotificationService? notificationService;

  const RemindersScreen({super.key, this.backend, this.notificationService});

  @override
  State<RemindersScreen> createState() => _RemindersScreenState();
}

class _RemindersScreenState extends State<RemindersScreen> {
  late final TabsBackend _backend;
  late final ReminderNotificationService _notifs;
  bool _loading = true;
  bool _failed = false;
  bool _loadFailed = false; // profile itself was null (auth/network)
  bool _writing = false; // a whole-list push is in flight (Vera B3)
  ReminderDocument _doc = ReminderDocument.empty;

  @override
  void initState() {
    super.initState();
    _backend = widget.backend ?? TabsBackend();
    _notifs =
        widget.notificationService ?? LocalReminderNotificationService();
    _load();
  }

  Future<void> _load({bool reconcile = true}) async {
    setState(() {
      _loading = true;
      _failed = false;
      _loadFailed = false;
    });
    try {
      final profile = await _backend.fetchProfile();
      if (!mounted) return;
      if (profile == null) {
        setState(() {
          _loading = false;
          _loadFailed = true;
        });
        return;
      }
      final rows =
          TabsBackend.decodeProfileList(profile['reminders']);
      setState(() {
        _doc = ReminderDocument.fromRawRows(rows);
        _loading = false;
      });
      if (reconcile) unawaited(_reconcileAlarms());
    } catch (_) {
      if (!mounted) return;
      setState(() {
        _loading = false;
        _failed = true;
      });
    }
  }

  /// Load-time safety net (native pull-reschedule parity): FULL
  /// reconcile — resync every reminder's alarms from the pulled
  /// list. Failures are isolated per reminder (see
  /// [reconcileReminderAlarms]) — a scheduling problem must never
  /// break the screen; the next successful write reconciles again.
  /// Returns whether every reminder synced cleanly.
  Future<bool> _reconcileAlarms() {
    return reconcileReminderAlarms(_notifs, [
      for (final i in _doc.visibleIndices)
        if (_doc.modelAt(i) != null) _doc.modelAt(i)!,
    ]);
  }

  void _showSaveError() {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
        content: Text(
            'Could not save that change. Check your connection and try again.')));
  }

  void _showAlarmNote() {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
        content: Text(
            'Saved. The alarm could not be scheduled — check notification permissions.')));
  }

  /// Applies [newDoc] optimistically, pushes the WHOLE list, and —
  /// after a successful push — runs the alarm side: for a delete,
  /// [cancelledReminderId]'s whole block is cancelled first, then a
  /// FULL reconcile across all current reminders reschedules every
  /// survivor (including one that shared the deleted row's id,
  /// Vera B4). On push failure: error SnackBar + reload from the
  /// server (no phantom state).
  ///
  /// SERIALIZED (Vera B3): at most one call runs at a time. While
  /// [_writing] is set, the write controls are disabled and every
  /// entry point drops its tap; the flag is held across the
  /// failure-path reload, so the reload can never race a push that
  /// is still in flight.
  Future<void> _applyAndPush(
    ReminderDocument newDoc, {
    int? cancelledReminderId,
  }) async {
    if (_writing) return;
    _writing = true;
    if (mounted) setState(() => _doc = newDoc);
    try {
      final ok = await _backend.postSyncProfile(
          {'reminders': jsonEncode(newDoc.encode())});
      if (ok) {
        _backend.invalidateSyncPull();
        var alarmsOk = true;
        if (cancelledReminderId != null) {
          try {
            await cancelReminderAlarms(_notifs, cancelledReminderId);
          } catch (_) {
            alarmsOk = false;
          }
        }
        // A notification failure NEVER fails the save.
        if (!await _reconcileAlarms()) alarmsOk = false;
        if (!alarmsOk) _showAlarmNote();
        return;
      }
      _showSaveError();
      _backend.invalidateSyncPull();
      await _load(reconcile: false);
    } finally {
      _writing = false;
      if (mounted) setState(() {});
    }
  }

  Future<void> _toggleReminder(int rawIndex, bool enabled) async {
    if (_writing) return;
    final newDoc = _doc.toggledAt(rawIndex, enabled);
    if (identical(newDoc, _doc)) return;
    await _applyAndPush(newDoc);
  }

  Future<void> _deleteReminder(int rawIndex) async {
    if (_writing) return;
    final id = _doc.modelAt(rawIndex)?.id ??
        reminderRowId(_doc.rawRows[rawIndex]);
    final newDoc = _doc.removedAt(rawIndex);
    if (identical(newDoc, _doc)) return;
    await _applyAndPush(newDoc, cancelledReminderId: id);
  }

  /// CREATE-only permission gate (Juno F1) — now the shared
  /// [runReminderCreatePermissionGate] above, which this screen
  /// and the Health Coach both run with the same ordering and
  /// copy. The Reminders behaviour is unchanged: on a system
  /// request failure the alarm note shows, and the editor sheet
  /// opens ONLY when notification permission is granted.
  /// Returns whether the sheet may open.
  Future<bool> _runCreatePermissionGate() {
    return runReminderCreatePermissionGate(
      context: context,
      notifs: _notifs,
      onNotificationsRequestError: _showAlarmNote,
    );
  }

  /// Opens the editor sheet. CREATE (the FAB) runs the permission
  /// gate first (see [_runCreatePermissionGate]); EDIT (card tap)
  /// does NOT run the gate — native has no edit UI, and editing an
  /// existing reminder must not be blocked by a create-time gate
  /// (Juno minor). Taps are dropped while a write is in flight
  /// (Vera B3).
  Future<void> _openEditor({ReminderModel? initial, int? rawIndex}) async {
    if (_writing) return;
    if (rawIndex == null) {
      final granted = await _runCreatePermissionGate();
      if (!granted || !mounted) return;
    }
    final row = await showModalBottomSheet<Map<String, dynamic>>(
      context: context,
      isScrollControlled: true,
      backgroundColor: NotelColors.background,
      builder: (_) => _ReminderSheet(initial: initial),
    );
    if (row == null || !mounted) return;
    if (rawIndex == null) {
      final newRow = {...row, 'id': nextReminderId(_doc.rawRows)};
      final newDoc = _doc.appended(newRow);
      await _applyAndPush(newDoc);
    } else {
      final existingId = _doc.modelAt(rawIndex)?.id ??
          reminderRowId(_doc.rawRows[rawIndex]) ??
          0;
      final merged = {..._doc.rawRows[rawIndex], ...row, 'id': existingId};
      final newDoc = _doc.replacedAt(rawIndex, merged);
      await _applyAndPush(newDoc);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: NotelColors.background,
      appBar: AppBar(
        backgroundColor: NotelColors.background,
        elevation: 0,
        leading: IconButton(
          icon: const Icon(
            Icons.arrow_back,
            color: NotelColors.textPrimary,
            semanticLabel: 'Back',
          ),
          onPressed: () => Navigator.of(context).pop(),
        ),
        title: const Text(
          'Reminders',
          style: TextStyle(
            fontSize: 20,
            fontWeight: FontWeight.bold,
            color: NotelColors.textPrimary,
          ),
        ),
      ),
      floatingActionButton: FloatingActionButton.extended(
        backgroundColor: NotelColors.primary,
        onPressed: _writing ? null : () => _openEditor(),
        icon: const Icon(Icons.add, color: Colors.white),
        label: const Text(
          'New Reminder',
          style: TextStyle(color: Colors.white, fontWeight: FontWeight.bold),
        ),
      ),
      body: _buildBody(),
    );
  }

  Widget _buildBody() {
    if (_loading) {
      return const Center(
        child: CircularProgressIndicator(color: NotelColors.primary),
      );
    }
    if (_failed || _loadFailed) {
      return _failureState();
    }
    final visible = _doc.visibleIndices;
    if (visible.isEmpty) {
      return const Center(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
