/// Mutable per-day row state for the editor sheet (Mon→Sun order).
class _DayRow {
  final int dayOfWeek; // Calendar constant
  final String dayName;
  bool enabled;
  TimeOfDay time;

  _DayRow({
    required this.dayOfWeek,
    required this.dayName,
    required this.enabled,
    required this.time,
  });
}

/// Port of native `AddReminderSheet`: title (only validation:
/// non-blank, trimmed), type chips "Set Time" (FIXED) / "Repeating"
/// (INTERVAL, default FIXED), a FIXED time (sheet default 8:00) or
/// the "Custom days & times" switch replacing it with 7 Mon–Sun
/// rows (each default disabled at 9:00), or the INTERVAL picker
/// (1..60 minutes XOR 1..5 hours, default 2h) with start (8:00) and
/// end (21:00). Pops a native-shaped row map (see
/// [buildReminderRow]); the caller assigns/preserves the `id`.
class _ReminderSheet extends StatefulWidget {
  final ReminderModel? initial;

  const _ReminderSheet({this.initial});

  @override
  State<_ReminderSheet> createState() => _ReminderSheetState();
}

class _ReminderSheetState extends State<_ReminderSheet> {
  late final TextEditingController _title;
  late String _type;
  late TimeOfDay _fixed;
  late bool _customDays;
  late List<_DayRow> _days;
  late int _intervalValue;
  late String _intervalUnit; // 'hours' | 'minutes'
  // Round 48 — set when the user actually changes an interval
  // control. The picker can only represent an XOR interval
  // (hours 1..5 or minutes 1..60), so an INTERVAL reminder whose
  // stored pair is zero (0h 0m — the alarm sync treats it as "no
  // slots") or mixed (e.g. 1h 30m) would be silently REWRITTEN
  // by a title-only edit. While untouched, [_save] writes the
  // stored pair back verbatim instead of the picker's view.
  bool _intervalDirty = false;
  late TimeOfDay _start;
  late TimeOfDay _end;

  static const _dayNames = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  static const _dayConstants = [2, 3, 4, 5, 6, 7, 1]; // Mon..Sun

  @override
  void initState() {
    super.initState();
    final initial = widget.initial;
    _title = TextEditingController(text: initial?.title ?? '')
      ..addListener(() => setState(() {}));
    _type = initial?.type ?? 'FIXED';
    _fixed = TimeOfDay(
      hour: initial?.fixedHour ?? 8,
      minute: initial?.fixedMinute ?? 0,
    );
    _customDays = initial != null && initial.dayConfigs.isNotEmpty;
    _days = [
      for (var i = 0; i < 7; i++)
        () {
          DayTimeConfig? existing;
          for (final d in initial?.dayConfigs ?? const <DayTimeConfig>[]) {
            if (d.dayOfWeek == _dayConstants[i]) {
              existing = d;
              break;
            }
          }
          return _DayRow(
            dayOfWeek: _dayConstants[i],
            dayName: _dayNames[i],
            enabled: existing?.isEnabled ?? false,
            time: TimeOfDay(
              hour: existing?.hour ?? 9,
              minute: existing?.minute ?? 0,
            ),
          );
        }(),
    ];
    if (initial != null && initial.intervalHours > 0) {
      _intervalUnit = 'hours';
      _intervalValue = initial.intervalHours;
    } else if (initial != null && initial.intervalMinutes > 0) {
      _intervalUnit = 'minutes';
      _intervalValue = initial.intervalMinutes;
    } else {
      _intervalUnit = 'hours';
      _intervalValue = 2;
    }
    _start = TimeOfDay(
      hour: initial?.startHour ?? 8,
      minute: initial?.startMinute ?? 0,
    );
    _end = TimeOfDay(
      hour: initial?.endHour ?? 21,
      minute: initial?.endMinute ?? 0,
    );
  }

  @override
  void dispose() {
    _title.dispose();
    super.dispose();
  }

  Future<void> _pickTime(TimeOfDay current, ValueChanged<TimeOfDay> set) async {
    final picked = await showTimePicker(
      context: context,
      initialTime: current,
      builder: (context, child) => Theme(
        data: Theme.of(context).copyWith(
          colorScheme: Theme.of(context)
              .colorScheme
              .copyWith(primary: NotelColors.primary),
        ),
        child: child!,
      ),
    );
    if (picked != null) setState(() => set(picked));
  }

  void _save() {
    final title = _title.text.trim();
    if (title.isEmpty) return;
    // Round 48 — untouched interval on an INTERVAL reminder:
    // preserve the stored pair verbatim (see [_intervalDirty]).
    // Only applies when the reminder being edited IS an interval
    // reminder — a FIXED reminder switched to Repeating in this
    // sheet saves the picker's displayed value, as shown.
    final initial = widget.initial;
    final preserveInterval =
        !_intervalDirty && initial != null && initial.type == 'INTERVAL';
    Navigator.of(context).pop(buildReminderRow(
      id: widget.initial?.id ?? 0,
      title: title,
      type: _type,
      fixedHour: _fixed.hour,
      fixedMinute: _fixed.minute,
      intervalHours: preserveInterval
          ? initial.intervalHours
          : _intervalUnit == 'hours'
              ? _intervalValue
              : 0,
      intervalMinutes: preserveInterval
          ? initial.intervalMinutes
          : _intervalUnit == 'minutes'
              ? _intervalValue
              : 0,
      startHour: _start.hour,
      startMinute: _start.minute,
      endHour: _end.hour,
      endMinute: _end.minute,
      isEnabled: widget.initial?.isEnabled ?? true,
      customDays: _customDays,
      dayConfigs: [
        for (final d in _days)
          DayTimeConfig(
            dayOfWeek: d.dayOfWeek,
            dayName: d.dayName,
            isEnabled: d.enabled,
            hour: d.time.hour,
            minute: d.time.minute,
          ),
      ],
    ));
  }

  Widget _timeRow(String label, TimeOfDay value, ValueChanged<TimeOfDay> set) {
    return ListTile(
      contentPadding: EdgeInsets.zero,
      title: Text(
        label,
        style: const TextStyle(
          color: NotelColors.textPrimary,
          fontSize: 14,
          fontWeight: FontWeight.w600,
        ),
      ),
      trailing: TextButton(
        onPressed: () => _pickTime(value, set),
        child: Text(
          formatTime12h(value.hour, value.minute),
          style: const TextStyle(
            color: NotelColors.primary,
            fontSize: 14,
            fontWeight: FontWeight.bold,
          ),
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final titleBlank = _title.text.trim().isEmpty;
    return Padding(
      padding: EdgeInsets.only(
        left: 20,
        right: 20,
        top: 20,
        bottom: MediaQuery.of(context).viewInsets.bottom + 20,
      ),
      child: SingleChildScrollView(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              widget.initial == null ? 'New Reminder' : 'Edit Reminder',
              style: const TextStyle(
                color: NotelColors.textPrimary,
                fontSize: 18,
                fontWeight: FontWeight.bold,
              ),
            ),
            const SizedBox(height: 16),
            TextField(
              controller: _title,
              autofocus: widget.initial == null,
              style: const TextStyle(color: NotelColors.textPrimary),
              decoration: const InputDecoration(
                labelText: 'Title',
                hintText: 'Reminder title',
              ),
              textInputAction: TextInputAction.done,
              onSubmitted: (_) {
                if (!titleBlank) _save();
              },
            ),
            const SizedBox(height: 16),
            Row(
              children: [
                ChoiceChip(
                  label: const Text('Set Time'),
                  selected: _type == 'FIXED',
                  onSelected: (_) => setState(() => _type = 'FIXED'),
                ),
                const SizedBox(width: 8),
                ChoiceChip(
                  label: const Text('Repeating'),
                  selected: _type == 'INTERVAL',
                  onSelected: (_) => setState(() => _type = 'INTERVAL'),
                ),
              ],
            ),
            const SizedBox(height: 8),
            if (_type == 'FIXED') ...[
              if (!_customDays)
                _timeRow('Time', _fixed, (t) => _fixed = t),
              SwitchListTile(
                contentPadding: EdgeInsets.zero,
                title: const Text(
                  'Custom days & times',
                  style: TextStyle(
                    color: NotelColors.textPrimary,
                    fontSize: 14,
                    fontWeight: FontWeight.w600,
                  ),
                ),
                value: _customDays,
                activeThumbColor: NotelColors.primary,
                onChanged: (v) => setState(() => _customDays = v),
              ),
              if (_customDays)
                for (final d in _days)
                  Row(
                    children: [
                      Checkbox(
                        value: d.enabled,
                        activeColor: NotelColors.primary,
                        onChanged: (v) =>
                            setState(() => d.enabled = v ?? false),
                      ),
                      Text(
                        d.dayName,
                        style: const TextStyle(
                          color: NotelColors.textPrimary,
                          fontSize: 14,
                        ),
                      ),
                      const Spacer(),
                      TextButton(
                        onPressed: () =>
                            _pickTime(d.time, (t) => d.time = t),
                        child: Text(
                          formatTime12h(d.time.hour, d.time.minute),
                          style: const TextStyle(
                            color: NotelColors.primary,
                            fontWeight: FontWeight.bold,
                          ),
                        ),
                      ),
                    ],
                  ),
            ] else ...[
              Row(
                children: [
                  const Text(
                    'Every',
                    style: TextStyle(
                      color: NotelColors.textPrimary,
                      fontSize: 14,
                      fontWeight: FontWeight.w600,
                    ),
                  ),
                  const SizedBox(width: 12),
                  DropdownButton<int>(
                    value: _intervalValue,
                    items: [
                      for (var v = 1;
                          v <= (_intervalUnit == 'hours' ? 5 : 60);
                          v++)
                        DropdownMenuItem(value: v, child: Text('$v')),
                    ],
                    onChanged: (v) {
                      if (v != null) {
                        setState(() {
                          _intervalValue = v;
                          _intervalDirty = true;
                        });
                      }
                    },
                  ),
                  const SizedBox(width: 12),
                  DropdownButton<String>(
                    value: _intervalUnit,
                    items: const [
                      DropdownMenuItem(
                          value: 'minutes', child: Text('minutes')),
                      DropdownMenuItem(
                          value: 'hours', child: Text('hours')),
                    ],
                    onChanged: (v) {
                      if (v == null) return;
                      setState(() {
                        _intervalUnit = v;
                        _intervalDirty = true;
                        if (v == 'hours' && _intervalValue > 5) {
                          _intervalValue = 5;
                        }
                      });
                    },
                  ),
                ],
              ),
              _timeRow('Start', _start, (t) => _start = t),
              _timeRow('End', _end, (t) => _end = t),
            ],
            const SizedBox(height: 16),
            Row(
              mainAxisAlignment: MainAxisAlignment.end,
              children: [
                TextButton(
                  onPressed: () => Navigator.of(context).pop(),
                  child: const Text('Cancel'),
                ),
                const SizedBox(width: 8),
                FilledButton(
                  onPressed: titleBlank ? null : _save,
                  style: FilledButton.styleFrom(
                      backgroundColor: NotelColors.primary),
                  child: const Text('Save'),
                ),
              ],
            ),
          ],
        ),
      ),
    );
  }
}
